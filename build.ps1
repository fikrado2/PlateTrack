# PlateTrack build script (PowerShell)
# Requires: PyInstaller, Inno Setup (ISCC.exe must be in PATH)

$ErrorActionPreference = "Stop"
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Definition
Set-Location $scriptDir

Write-Host "=== PlateTrack build script started ===" -ForegroundColor Cyan

# -------------------- 1. Clean --------------------
Write-Host "Cleaning previous build artifacts..." -ForegroundColor Yellow
Remove-Item -Recurse -Force build dist 2>$null
if (Test-Path "PlateTrack.exe") { Remove-Item PlateTrack.exe -Force }

# -------------------- 2. Ensure dependencies --------------------
Write-Host "Checking Python and packages..." -ForegroundColor Yellow
$py = python
if (-not ($py)) { Write-Error "Python not found in PATH"; exit 1 }

# Install PyInstaller if missing
$pipList = pip list
if ($pipList -notmatch "PyInstaller") {
    Write-Host "Installing PyInstaller..." -ForegroundColor Yellow
    pip install pyinstaller
}

# -------------------- 3. PyInstaller --------------------
Write-Host "Running PyInstaller..." -ForegroundColor Yellow
pyinstaller PlateTrack.spec --clean --noconfirm
if (-not (Test-Path "dist/PlateTrack.exe")) {
    Write-Error "PyInstaller failed to produce PlateTrack.exe"
    exit 1
}
Write-Host "PyInstaller completed." -ForegroundColor Green

# -------------------- 4. Inno Setup --------------------
Write-Host "Checking for Inno Setup compiler (ISCC)..." -ForegroundColor Yellow
if (-not (Get-Command iscc -ErrorAction SilentlyContinue)) {
    Write-Error "ISCC.exe not found. Please install Inno Setup and add its folder to PATH."
    exit 1
}

# Create Inno Setup script
$issPath = "$scriptDir\PlateTrack.iss"
if (Test-Path $issPath) { Remove-Item $issPath -Force }

$issContent = @"
; PlateTrack installer script
; Generated by build.ps1 – do not modify manually

[Setup]
AppName=${{APP_NAME}}
AppVersion=${{APP_VERSION}}
AppPublisher=${{APP_PUBLISHER}}
DefaultDirName={{autopf}}\${{APP_NAME}}
DefaultGroupName=${{APP_NAME}}
UninstallDisplayIcon=${{APP_PATH}}\PlateTrack.exe
OutputBaseFilename=PlateTrack-Setup-${{APP_VERSION}}
Compression=lzma
SolidCompression=yes
EnableDirDoesntExist=no
DisableProgramGroupPage=no
LicenseFile=LICENSE
InfoBeforeFile=README.md
WizardImageFile=assets\splash.png
WizardSmallImageFile=assets\icon.ico
DisableDirPage=auto
DisableReadyPage=auto
UninstallDisplayName=${{APP_NAME}} ${{APP_VERSION}}
ChangesAssociations=no
WelcomeLabel2=Click Install to setup PlateTrack.

[Files]
Source: "dist\PlateTrack.exe"; DestDir: "{app}"; Flags: ignoreversion
Source: "assets\*"; DestDir: "{app}\assets"; Flags: ignoreversion recursesubdirs createallsubdirs
Source: "LICENSE"; DestDir: "{app}"; Flags: ignoreversion
Source: "README.md"; DestDir: "{app}"; Flags: ignoreversion
Source: "CHANGELOG.md"; DestDir: "{app}"; Flags: ignoreversion

; Create empty data folder (will be populated on first run)
; Note: Inno Setup cannot create a folder that is excluded from uninstall,
; so we create it and later the app will create subfolders as needed.
Source: "dataplaceholder.txt"; DestDir: "{app}\data"; Flags: ignoreversion

[Dirs]
Name: "{app}\data"; Flags: uninsneveruninstall
Name: "{app}\logs"; Flags: uninsneveruninstall
Name: "{app}\snapshots"; Flags: uninsneveruninstall
Name: "{app}\exports"; Flags: uninsneveruninstall
Name: "{app}\models"; Flags: uninsneveruninstall

[Icons]
Name: "{group}\${{APP_NAME}}"; Filename: "{app}\PlateTrack.exe"
Name: "{commondesktop}\${{APP_NAME}}"; Filename: "{app}\PlateTrack.exe"; Tasks: desktopicon

[Tasks]
Name: "desktopicon"; Description: "{{cm:DesktopIcon}}"; GroupDescription: "{{cm:AdditionalIcons}}"; Flags: unchecked

[Run]
Filename: "{app}\PlateTrack.exe"; Description: "{{cm:LaunchApplication,${{STRING#PlateTrackWin}}"; Flags: nowait postinstall skipifsilent

[Languages]
Name: "english"; MessagesFile: "compiler:Default.Isl"

[CustomMessages]
english.APP_NAME=${{APP_NAME}}
english.APP_VERSION=${{APP_VERSION}}
english.APP_PUBLISHER=${{APP_PUBLISHER}}
english.APP_PATH={app}
english.PlateTrackWin=PlateTrack v${{APP_VERSION}} by ${{APP_PUBLISHER}}
"@

# Replace placeholders
$appName = "PlateTrack"
$appVersion = (Get-Content version.py).Trim()
$appPublisher = "Fikrado Security"
$issContent = $issContent -replace "\$\{APP_NAME\}", $appName
$issContent = $issContent -replace "\$\{APP_VERSION\}", $appVersion
$issContent = $issContent -replace "\$\{APP_PUBLISHER\}", $appPublisher

Set-Content -Path $issPath -Value $issContent -Encoding UTF8

# Create a dummy placeholder for the data folder (will be removed by Inno Setup? we keep it)
Set-Content -Path "$scriptDir\dataplaceholder.txt" -Value "This file ensures the data folder is created." -Encoding UTF8

Write-Host "Running ISCC..." -ForegroundColor Yellow
& iscc $issPath
if ($LASTEXITCODE -ne 0) {
    Write-Error "ISCC failed with exit code $LASTEXITCODE"
    exit 1
}
Write-Host "Inno Setup completed." -ForegroundColor Green

# -------------------- 5. Output ----------------->
Write-Host "=== Build successful ===" -ForegroundColor Green
Write-Host "Installer: $scriptDir\Output\PlateTrack-Setup-$appVersion.exe" -ForegroundColor Cyan
# Ensure Output folder exists
$outputDir = "$scriptDir\Output"
if (-not (Test-Path $outputDir)) { New-Item -ItemType Directory -Path $outputDir | Out-Null }
Move-Item -Force "$scriptDir\PlateTrack-Setup-$appVersion.exe" "$outputDir\" 2>$null

# Cleanup temporary placeholder
Remove-Item "$scriptDir\dataplaceholder.txt" -Force

Write-Host "You can now run the installer from the Output folder." -ForegroundColor Yellow